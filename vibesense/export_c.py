"""Train a SMALL forest and export it as a C header for an ESP32-class chip.

The dashboard uses the bigger models in models/. The embedded model is deliberately tiny
(few shallow trees) so it fits in a few KB of flash and needs no ML library on the chip.
"""
import json
from pathlib import Path

import numpy as np
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split

from .features import FEATURE_NAMES, extract_many
from .simulator import STATES, make_dataset

ROOT = Path(__file__).resolve().parent.parent
N_TREES, DEPTH = 10, 6


def fl(x, digits=9):
    """C float literal that is always valid (0 -> 0.0f, 74 -> 74.0f)."""
    t = f"{x:.{digits}g}"
    if "." not in t and "e" not in t and "inf" not in t and "nan" not in t:
        t += ".0"
    return t + "f"


def _tree_arrays(est, leaf_fn):
    t = est.tree_
    return t.feature.copy(), t.threshold.copy(), t.children_left.copy(), t.children_right.copy(), [leaf_fn(t, i) for i in range(t.node_count)]


def _emit(name, trees, ncls):
    """Concatenate trees into flat arrays with a root-offset table."""
    feat, thr, left, right, val, roots = [], [], [], [], [], []
    for f, th, l, r, v in trees:
        off = len(feat)
        roots.append(off)
        for i in range(len(f)):
            feat.append(int(f[i]) if l[i] != -1 else -1)
            thr.append(float(th[i]) if l[i] != -1 else 0.0)
            left.append(int(l[i]) + off if l[i] != -1 else -1)
            right.append(int(r[i]) + off if r[i] != -1 else -1)
            val.append(v[i])
    n = len(feat)
    out = [f"#define {name}_TREES {len(trees)}", f"#define {name}_NODES {n}"]
    out.append(f"static const int16_t {name}_ROOT[{len(trees)}] = {{{', '.join(map(str, roots))}}};")
    out.append(f"static const int8_t {name}_FEAT[{n}] = {{{', '.join(map(str, feat))}}};")
    out.append(f"static const float {name}_THR[{n}] = {{{', '.join(fl(x) for x in thr)}}};")
    out.append(f"static const int16_t {name}_LEFT[{n}] = {{{', '.join(map(str, left))}}};")
    out.append(f"static const int16_t {name}_RIGHT[{n}] = {{{', '.join(map(str, right))}}};")
    if ncls:
        flat = ", ".join("{" + ", ".join(fl(x, 6) for x in v) + "}" for v in val)
        out.append(f"static const float {name}_VAL[{n}][{ncls}] = {{{flat}}};")
    else:
        out.append(f"static const float {name}_VAL[{n}] = {{{', '.join(fl(v, 6) for v in val)}}};")
    return "\n".join(out), n


def main(seed=0):
    X, y, sev = make_dataset(400, seed)
    F = extract_many(X)
    Ftr, Fte, ytr, yte, str_, ste = train_test_split(F, y, sev, test_size=0.25, stratify=y, random_state=seed)
    clf = RandomForestClassifier(n_estimators=N_TREES, max_depth=DEPTH, random_state=seed).fit(Ftr, ytr)
    reg = RandomForestRegressor(n_estimators=N_TREES, max_depth=DEPTH, random_state=seed).fit(Ftr, str_)
    acc = float(accuracy_score(yte, clf.predict(Fte)))
    mae = float(np.mean(np.abs(reg.predict(Fte) - ste)))

    def clf_leaf(t, i):
        v = t.value[i][0]
        return list(v / v.sum())

    ctrees = [_tree_arrays(e, clf_leaf) for e in clf.estimators_]
    rtrees = [_tree_arrays(e, lambda t, i: float(t.value[i][0][0])) for e in reg.estimators_]
    c_src, cn = _emit("CLF", ctrees, len(STATES))
    r_src, rn = _emit("REG", rtrees, 0)
    header = f"""// AUTO-GENERATED by vibesense/export_c.py. Do not edit by hand.
// Small forest: {N_TREES} trees, max depth {DEPTH}. Trained on SIMULATED data only.
#ifndef VIBESENSE_MODEL_H
#define VIBESENSE_MODEL_H
#include <stdint.h>
#define N_FEATURES {len(FEATURE_NAMES)}
#define N_CLASSES {len(STATES)}
// classes: {', '.join(STATES)}
{c_src}
{r_src}
#endif
"""
    out_dir = ROOT / "firmware" / "wokwi"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "model.h").write_text(header)
    flash_bytes = cn * (1 + 4 + 2 + 2 + 4 * len(STATES)) + rn * (1 + 4 + 2 + 2 + 4)
    info = {"trees": N_TREES, "max_depth": DEPTH, "clf_nodes": cn, "reg_nodes": rn,
            "approx_flash_bytes": flash_bytes, "accuracy_small_model": acc, "severity_mae_small_model": mae}
    (ROOT / "models" / "embedded_metrics.json").write_text(json.dumps(info, indent=2))
    # reference data for the C parity test: 40 windows + python predictions from the SAME small model
    rng = np.random.default_rng(123)
    from .simulator import make_window
    ref = {"windows": [], "states": [], "features": [], "clf_proba": [], "sev": []}
    for k in range(40):
        s = STATES[k % 4]
        w = make_window(s, rng.uniform(0.1, 1.0) if s != "healthy" else 0.0, rng)
        f = extract_many([w])[0]
        ref["windows"].append([float(v) for v in w])
        ref["states"].append(s)
        ref["features"].append([float(v) for v in f])
        ref["clf_proba"].append([float(v) for v in clf.predict_proba([f])[0]])
        ref["sev"].append(float(reg.predict([f])[0]))
    (ROOT / "firmware" / "reference.json").write_text(json.dumps(ref))
    print(json.dumps(info, indent=2))


if __name__ == "__main__":
    main()
